  private fun generateScienceItem(
    id: String, grade: String, subject: String, setNumber: Int, qIndex: Int, globalIdx: Int, unit: String, type: String
  ): StructuredEssayItem {
    val totalMarks = if (type == "STRUCTURED") 15 else 20
    val subQuestions = StructuredEssayDynamicContentProvider.buildSubQuestions(grade, subject, unit, type, qIndex, setNumber)
    val (qTitle, qScenario) = StructuredEssayDynamicContentProvider.getTitleAndScenario(grade, subject, unit, type, qIndex, setNumber)

    return StructuredEssayItem(
      id = id,
      grade = grade,
      subject = subject,
      topicSinhala = qTitle,
      type = type,
      totalMarks = totalMarks,
      mainScenario = qScenario,
      subQuestions = subQuestions,
