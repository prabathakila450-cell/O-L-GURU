  // Generates 400 unique, curriculum-aligned flashcard items (20 sets x 20 cards)
  private fun generate400Cards(grade: String, subject: String): List<FlashcardDeckItem> {
    val themes = getUnitThemesForSubject(grade, subject)
    val list = ArrayList<FlashcardDeckItem>(400)

    for (setNum in 1..20) {
      val theme = themes.getOrElse(setNum - 1) { "විෂය ඒකකය - $setNum" }
      val cardsInSet = generate20CardsForSet(grade, subject, setNum, theme)
      list.addAll(cardsInSet)
    }

    return list
  }

  private fun generate20CardsForSet(
    grade: String,
    subject: String,
    setNum: Int,
    theme: String
  ): List<FlashcardDeckItem> {
    val baseIndex = (setNum - 1) * 20

    return (1..20).map { cardInSet ->
      val globalIdx = baseIndex + cardInSet
      val (q, a, tip, fact) = getCardContent(grade, subject, setNum, cardInSet, globalIdx, theme)
      val cleanQuestion = q.replace(Regex("""^\[.*?\]\s*"""), "")
      FlashcardDeckItem(
        id = "fc_${grade}_${subject.hashCode()}_${globalIdx}",
        grade = grade,
        subject = subject,
        setNumber = setNum,
        cardIndexInSet = cardInSet,
        globalIndex = globalIdx,
        questionFront = cleanQuestion,
        answerBack = a,
        explanationTip = tip,
        formulaOrFact = fact,
        unitCategory = theme
      )
    }
  }

  private fun getCardContent(
    grade: String,
    subject: String,
    setNum: Int,
    cardInSet: Int,
    globalIdx: Int,
    theme: String
  ): CardContentTuple {
    return FlashcardDynamicContentProvider.getContent(subject, grade, setNum, cardInSet, globalIdx, theme)
  }
