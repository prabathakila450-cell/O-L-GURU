data class FlashcardDeckItem(
  val id: String,
  val grade: String, // "9", "10", "11"
  val subject: String,
  val setNumber: Int, // 1 to 20
  val cardIndexInSet: Int, // 1 to 20
  val globalIndex: Int, // 1 to 400
  val questionFront: String,
  val answerBack: String,
  val explanationTip: String,
  val formulaOrFact: String = "",
  val unitCategory: String = "",
  var isMastered: Boolean = false,
  var needsReview: Boolean = false
)

data class FlashcardSetInfo(
  val setNumber: Int, // 1..20
  val title: String,
  val startCardNum: Int, // e.g. 1
  val endCardNum: Int, // e.g. 20
  val totalCards: Int = 20,
